pub(crate) const FAMILY: FamilyKey = FamilyKey::new("poot_fixture_neoxish");

/// The HF `model_type` that names the family.
const MODEL_TYPE: &str = "poot_fixture_neoxish";

/// The registry entry: what `Registry::builtin_plus` takes. The family is its keys, its config and
/// its tensor names; the stack, the layer and the model are the shared ones.
pub(crate) const ENTRY: FamilyEntry = entry::<Neoxish>();

/// The fixture family's own tool-call markup, one no built-in names: `@neoxish <name> <arguments>`.
#[derive(Debug)]
pub(crate) struct NeoxishToolCodec;

impl ToolCallCodec for NeoxishToolCodec {
    fn parse(&self, text: &str) -> Vec<ParsedToolCall> {
        text.strip_prefix("@neoxish ")
            .and_then(|rest| rest.split_once(' '))
            .map(|(name, arguments)| ParsedToolCall {
                name: name.to_string(),
                arguments: arguments.to_string(),
            })
            .into_iter()
            .collect()
    }

    fn forced_pattern(
        &self,
        _forced: &[(String, serde_json::Value)],
    ) -> poot_text::Result<Option<String>> {
        Ok(None)
    }
}

/// The vocabulary of the fixture checkpoint, and its end-of-sequence id.
pub(crate) const VOCAB: usize = 48;
pub(crate) const EOS: u32 = 47;

struct Neoxish;

impl StandardFamily for Neoxish {
    const FAMILY: FamilyKey = FAMILY;
    const KEYS: &'static [(ConfigSource, &'static str)] =
        &[(ConfigSource::HfModelType, MODEL_TYPE)];

    fn configure(raw: &RawConfig<'_>) -> Result<StandardParams, ModelError> {
        let fields = Fields::new(raw, FAMILY);
        let count = |name: &'static str| fields.count(Field::hf(name), None);
        let width = count("hidden_size")?;
        let heads = count("num_attention_heads")?;
        if !width.is_multiple_of(heads) {
            return Err(fields.error("hidden_size", ConfigReason::NotDivisible { by: heads }));
        }
        let head_dim = width / heads;
        // GPT-NeoX rotates `rotary_pct` of each head (a quarter here), rounded down to an even width.
        let pct = fields.float(Field::hf("rotary_pct"), 0.25)?;
        if !(pct.is_finite() && pct > 0.0 && pct <= 1.0) {
            return Err(fields.error("rotary_pct", ConfigReason::NotFinitePositive));
        }
        let rotary = ((head_dim as f32 * pct) as usize) & !1;
        let theta = fields.float(Field::hf("rotary_emb_base"), 10_000.0)?;
        let rope =
            RopeParams::new(rotary, theta, &RopeFlavor::Plain).map_err(|e| e.for_family(FAMILY))?;
        let attention = AttentionParams::new(heads, heads, head_dim, true, rope)
            .map_err(|e| e.for_family(FAMILY))?
            .with_out_bias();
        let eps = fields.float(Field::hf("layer_norm_eps"), 1e-5)?;
        let norm = NormParams::of(NormKind::Layer, eps).map_err(|e| e.for_family(FAMILY))?;
        let layers = count("num_hidden_layers")?;
        Ok(StandardParams {
            vocab: fields.vocab()?,
            width,
            layers,
            max_positions: count("max_position_embeddings")?,
            attention: vec![attention; layers],
            mlp: vec![
                Mlp::Plain {
                    inter: count("intermediate_size")?,
                    act: Gelu::Erf,
                    biased: true,
                };
                layers
            ],
            layer: LayerParams::new(norm),
            stack: StackParams::new(norm),
            norms: LayerNormKind::Biased,
            final_norm_bias: true,
            embed_norm: false,
            head_required: false,
            eos: fields.eos(None)?,
            bos: fields.bos()?,
            prompt_bos: None,
            chat: ChatFormat::ChatML,
            tool_codec: Some(Arc::new(NeoxishToolCodec)),
            embeddable: false,
        })
    }

    fn weights(
        _raw: &RawConfig<'_>,
        store: &WeightStore,
        params: &mut StandardParams,
    ) -> Result<WeightMap, ModelError> {
        weight_map(params, store)
    }
}

/// The checkpoint's tensor name table: where each role of the model sits in a GPT-NeoX checkpoint.
mod names {
    pub(super) const EMBED: &str = "gpt_neox.embed_in.weight";
    pub(super) const FINAL_NORM: &str = "gpt_neox.final_layer_norm.weight";
    pub(super) const FINAL_NORM_BIAS: &str = "gpt_neox.final_layer_norm.bias";
    pub(super) const HEAD: &str = "embed_out.weight";

    pub(super) fn layer(l: usize, tail: &str) -> String {
        format!("gpt_neox.layers.{l}.{tail}")
    }
}

/// The weight map of a `p`-shaped model over `store`. The fused `query_key_value` weight and bias are
/// each read three times, once per `q | k | v` row range, so a packed checkpoint would stay packed.
fn weight_map(p: &StandardParams, store: &WeightStore) -> Result<WeightMap, ModelError> {
    let weight_error = |source| ModelError::Weight {
        family: FAMILY,
        source,
    };
    let stored = |name: &str| WeightView::Stored(WeightKey::new(name));
    let (heads, head_dim) = (p.attention[0].heads(), p.attention[0].head_dim());
    let rows = heads * head_dim;
    let part = |key: String, i: usize| WeightView::RowRange {
        key: WeightKey::new(key),
        rows: i * rows..(i + 1) * rows,
    };
    let mut map = WeightMap::builder(store);
    let mut add = |id, view| map.map(id, view).map(|_| ()).map_err(weight_error);
    add(WeightId::model(WeightRole::Embed), stored(names::EMBED))?;
    add(
        WeightId::model(WeightRole::FinalNorm),
        stored(names::FINAL_NORM),
    )?;
    add(
        WeightId::model(WeightRole::FinalNormBias),
        stored(names::FINAL_NORM_BIAS),
    )?;
    add(WeightId::model(WeightRole::Head), stored(names::HEAD))?;
    for l in 0..p.layers {
        let id = |role| WeightId::layer(l, role);
        let name = |tail: &str| names::layer(l, tail);
        let norm = |role| WeightRole::Norm(role);
        let attn = |role| WeightRole::Attn(role);
        let ffn = |role| WeightRole::Ffn(role);
        for (role, tail) in [
            (norm(NormRole::Attn), "input_layernorm.weight"),
            (norm(NormRole::AttnBias), "input_layernorm.bias"),
            (norm(NormRole::Ffn), "post_attention_layernorm.weight"),
            (norm(NormRole::FfnBias), "post_attention_layernorm.bias"),
            (attn(AttnRole::O), "attention.dense.weight"),
            (attn(AttnRole::OBias), "attention.dense.bias"),
            (ffn(FfnRole::Up), "mlp.dense_h_to_4h.weight"),
            (ffn(FfnRole::UpBias), "mlp.dense_h_to_4h.bias"),
            (ffn(FfnRole::Down), "mlp.dense_4h_to_h.weight"),
            (ffn(FfnRole::DownBias), "mlp.dense_4h_to_h.bias"),
        ] {
            add(id(role), stored(&name(tail)))?;
        }
        for (i, (q, qb)) in [
            (AttnRole::Q, AttnRole::QBias),
            (AttnRole::K, AttnRole::KBias),
            (AttnRole::V, AttnRole::VBias),
        ]
        .into_iter()
        .enumerate()
        {
            add(
                id(attn(q)),
                part(name("attention.query_key_value.weight"), i),
            )?;
            add(
                id(attn(qb)),
                part(name("attention.query_key_value.bias"), i),
            )?;
        }
    }
    Ok(map.build())
}

/// The fixture's config: two layers of four 16-wide heads (RoPE over 4 dims of each), the 48-word
/// vocabulary of [`VOCAB`].
pub(crate) fn fixture_config() -> serde_json::Value {
    serde_json::json!({
        "model_type": MODEL_TYPE,
        "vocab_size": VOCAB,
        "hidden_size": 64,
        "intermediate_size": 128,
        "num_hidden_layers": 2,
        "num_attention_heads": 4,
        "rotary_pct": 0.25,
        "rotary_emb_base": 10000.0,
        "layer_norm_eps": 1e-5,
        "max_position_embeddings": 64,
        "tie_word_embeddings": false,
        "eos_token_id": EOS,
    })
}

/// Every tensor of a checkpoint of `config`'s dims, by its GPT-NeoX name.
fn fixture_shapes(config: &serde_json::Value) -> Vec<(String, Vec<usize>)> {
    let n = |f: &str| config[f].as_u64().unwrap() as usize;
    let (v, w, inter) = (n("vocab_size"), n("hidden_size"), n("intermediate_size"));
    let mut shapes = vec![
        (names::EMBED.to_string(), vec![v, w]),
        (names::FINAL_NORM.to_string(), vec![w]),
        (names::FINAL_NORM_BIAS.to_string(), vec![w]),
        (names::HEAD.to_string(), vec![v, w]),
    ];
    for l in 0..n("num_hidden_layers") {
        for (tail, shape) in [
            ("input_layernorm.weight", vec![w]),
            ("input_layernorm.bias", vec![w]),
            ("post_attention_layernorm.weight", vec![w]),
            ("post_attention_layernorm.bias", vec![w]),
            ("attention.query_key_value.weight", vec![3 * w, w]),
            ("attention.query_key_value.bias", vec![3 * w]),
            ("attention.dense.weight", vec![w, w]),
            ("attention.dense.bias", vec![w]),
            ("mlp.dense_h_to_4h.weight", vec![inter, w]),
            ("mlp.dense_h_to_4h.bias", vec![inter]),
            ("mlp.dense_4h_to_h.weight", vec![w, inter]),
            ("mlp.dense_4h_to_h.bias", vec![w]),
        ] {
            shapes.push((names::layer(l, tail), shape));
        }
    }
    shapes
}

/// How big a tensor's entries are, by what the tensor is: a norm scale sits near one, a norm or
/// projection bias is small, and the Q and K projections are large enough that attention scores
/// separate the positions (so a wrong position changes the tokens, not only the last digits).
fn magnitude(name: &str) -> (f32, f32) {
    // (centre, spread): entries are `centre + spread * u`, `u` uniform in [-0.5, 0.5).
    if name.ends_with("layernorm.weight") || name.ends_with("layer_norm.weight") {
        (1.0, 0.2)
    } else if name.ends_with(".bias") {
        (0.0, 0.1)
    } else if name.contains("query_key_value") {
        (0.0, QKV_SPREAD)
    } else {
        (0.0, 0.5)
    }
}

/// The spread of the fused `query_key_value` weight.
const QKV_SPREAD: f32 = 2.0;

/// The synthetic checkpoint `ENTRY` ships for tests: BF16 tensors of deterministic pseudo-random
/// values (one xorshift stream over every tensor in order), sized by [`magnitude`].
pub(crate) fn fixture() -> Fixture {
    let config = fixture_config();
    let mut store = WeightStore::builder();
    let mut seed = 0x9e37_79b9u32;
    for (name, shape) in fixture_shapes(&config) {
        let (centre, spread) = magnitude(&name);
        let n: usize = shape.iter().product();
        let mut bytes = Vec::with_capacity(2 * n);
        for _ in 0..n {
            seed ^= seed << 13;
            seed ^= seed >> 17;
            seed ^= seed << 5;
            let u = (seed >> 8) as f32 / (1u32 << 24) as f32 - 0.5;
            let value = centre + spread * u;
            bytes.extend_from_slice(&((value.to_bits() >> 16) as u16).to_le_bytes());
        }
        let dense = DenseWeight::try_new(DType::BF16, shape, bytes.into())
            .expect("the fixture bytes match their shape");
        store
            .insert(name, WeightEntry::Dense(dense))
            .expect("the fixture names are unique");
    }
    Fixture {
        config,
        generation: None,
        preprocessor: None,
        store: store.build(),
    }
}
