//! The whole fixture family of the add-a-model standing test (ADR-0104 rule 3): "neoxish", a GPT-NeoX
//! style decoder defined outside every production crate. It is not a shipped family: the config
//! reader, the checkpoint-name table, the registry entry and the fixture checkpoint are all here, built
//! from the public surface only (`poot_models::components`, `poot_models::registry`,
//! `poot_quant::weights`); the model itself is the shared `StandardFamily` wrapper. If adding it
//! needed a production edit, this file could not compile.
//!
//! What makes it a different model from every shipped one: LayerNorm with a bias on every norm, RoPE
//! over a quarter of each head, one fused `query_key_value` tensor bound through three
//! [`WeightView::RowRange`] views (and its fused bias the same way), a GELU MLP, and an untied head.
//!
//! Other test binaries include this file with `#[path = "add_a_model/family.rs"] mod family;`
//! instead of defining a second fixture family. Every pub item is used inside this file, so an
//! including binary needs no `#[allow(dead_code)]` and none may be added. Do not edit this file from
//! an including card.

