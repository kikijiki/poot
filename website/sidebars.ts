import type {SidebarsConfig} from '@docusaurus/plugin-content-docs';

// This runs in Node.js - Don't use client-side code here (browser APIs, JSX...)

// One sidebar per section folder of ./docs, named after the folder: the navbar is the only place for the
// top-level sections, and the sidebar lists only the pages of the current section. Page order is the
// `sidebar_position` frontmatter. A page outside these folders (Performance, Status, the docs home) has no
// sidebar. `bun scripts/check-navbar.mjs` checks that every section folder has its sidebar and navbar entry.
const section = (dirName: string) => [{type: 'autogenerated' as const, dirName}];

const sidebars: SidebarsConfig = {
  develop: section('develop'),
  serve: section('serve'),
  architecture: section('architecture'),
};

export default sidebars;
