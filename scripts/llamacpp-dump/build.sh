#!/usr/bin/env bash
# Build llamacpp-dump against the llama.cpp source and toolchain this repository's flake.lock pins: the
# `nixpkgs` input (inputs.nixpkgs in flake.nix) supplies `llama-cpp.src` (fixed-output, hash-checked: never a
# fresh clone), cmake, ninja and gcc, all through `--inputs-from <repo>` so nothing floats with the host's
# channel or registry. Prints the paths of llamacpp-dump, llamacpp-truncate and llamacpp-dequant-rows; stderr records the llama.cpp release it was built from.
#
#   scripts/llamacpp-dump/build.sh [out-dir]    # default: ${XDG_CACHE_HOME:-~/.cache}/poot/llamacpp-dump
#
# The dequant references (llama.cpp's own `to_float` per ggml type) are generated by a second, per-format
# program linked against the libraries this leaves in <out-dir>/build/bin: for IQ3_S,
# crates/poot-quant/tests/data/iq3_s_reference.cpp (build line in its header) writes iq3_s_reference.tsv.
set -euo pipefail

here=$(cd "$(dirname "$0")" && pwd)
repo=$(cd "$here/../.." && pwd)
out=${1:-${XDG_CACHE_HOME:-$HOME/.cache}/poot/llamacpp-dump}
mkdir -p "$out"

source=$(nix build --no-link --print-out-paths --inputs-from "$repo" nixpkgs#llama-cpp.src)
version=$(nix eval --raw --inputs-from "$repo" nixpkgs#llama-cpp.version)
echo "llama.cpp release b$version, source: $source" >&2

nix shell --inputs-from "$repo" nixpkgs#cmake nixpkgs#ninja nixpkgs#gcc -c bash -euo pipefail -c '
    cmake -S "$1" -B "$2/build" -G Ninja -DCMAKE_BUILD_TYPE=Release -DLLAMA_CURL=OFF \
        -DLLAMA_BUILD_TESTS=OFF -DLLAMA_BUILD_SERVER=OFF -DLLAMA_BUILD_EXAMPLES=OFF -DLLAMA_OPENSSL=OFF >&2
    cmake --build "$2/build" --target llama -j "$(nproc)" >&2
    g++ -O1 -std=c++17 "$3/dump.cpp" -I"$1/include" -I"$1/ggml/include" \
        -L"$2/build/bin" -lllama -lggml -lggml-base -Wl,-rpath,"$2/build/bin" -o "$2/llamacpp-dump"
    g++ -O1 -std=c++17 "$3/truncate.cpp" -I"$1/include" -I"$1/ggml/include" \
        -L"$2/build/bin" -lllama -lggml -lggml-base -Wl,-rpath,"$2/build/bin" -o "$2/llamacpp-truncate"
    g++ -O1 -std=c++17 "$3/dequant_rows.cpp" -I"$1/include" -I"$1/ggml/include" \
        -L"$2/build/bin" -lllama -lggml -lggml-base -Wl,-rpath,"$2/build/bin" -o "$2/llamacpp-dequant-rows"
' _ "$source" "$out" "$here"
echo "$out/llamacpp-dump $out/llamacpp-truncate $out/llamacpp-dequant-rows"
